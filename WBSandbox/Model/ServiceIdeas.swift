import SwiftUI

// Идеи на проверку. Отдельный раздел песочницы намеренно: в основные сценарии
// попадает только то, что подтверждено картой (PAYMENTS.md), а здесь лежат
// предложения — их можно показать, обсудить и выбросить, не трогая рабочие
// экраны.
//
// Каждая идея — копия рабочей спеки с одним отличием. Так на показе видно ровно
// то, что предлагается, а не «другой экран целиком».

enum ServiceIdeas {
    static let all: [ServiceSpec] = [repeatPayment]

    /// Повторный платёж.
    ///
    /// ЖКУ платят каждый месяц одним и тем же реквизитом, а форма каждый раз
    /// пустая: человек заново вводит лицевой счёт, который у банка уже есть. Идея —
    /// показать прошлый платёж строкой над формой: тап по кнопке подставляет
    /// реквизит и сразу спрашивает начисление, то есть форма из шести полей
    /// сворачивается в одно нажатие.
    ///
    /// Сумму прошлого месяца в кнопку не выносим: за новый период начислено своё, и
    /// цифра июля рядом со словом «оплатить» обещала бы не то, что спишется. Она
    /// стоит в строке как справка — «в июле было столько».
    static var repeatPayment: ServiceSpec {
        var spec = ServiceCatalog.mosenergo
        spec.id = "idea-repeat-payment"
        spec.demoName = "Повторный платёж"
        spec.lastPayment = LastPayment(
            period: "июль 2026",
            identifier: "8412034567",
            amount: Decimal(string: "3105.40")!
        )
        return spec
    }
}
