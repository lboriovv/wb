import SwiftUI

/// Живой фон транзакционного экрана: два размытых холма, дышащих у нижней кромки
/// секции с суммой. Сам эффект живёт в `Design/AmbientMounds.metal`, здесь —
/// только его эмоциональная настройка.
///
/// Вся эмоция сведена к одному числу `mood`, и это сделано намеренно: экран не
/// должен уметь «включать анимацию тревоги» — он лишь сообщает, насколько
/// напряжённый сейчас момент, а как это выглядит, решает слой.
///
///   0 — сумма пустая: холодный серый свет почти не виден, только угадывается;
///   1 — сумму набирают: холмы спокойно дышат, ничего не просит внимания;
///   2 — денег не хватает: холмы приседают, расползаются в стороны, светят
///       ярче и уходят в оранжевый.
///
/// Цвет включается только на третьем состоянии. Пока всё в порядке, фон обязан
/// быть бесцветным: цвет на платёжном экране — это сообщение, и если фон красит
/// собой спокойный ввод, ему потом нечем сказать, что что-то изменилось.
///
/// Сплющивание работает как указатель вниз: вся световая масса, которая только
/// что стояла в центре секции, за полсекунды оседает к её нижней кромке — ровно
/// на строку с остатком счёта, то есть туда, куда человеку и надо посмотреть.
/// Это подсказка без единого слова и без ещё одной плашки на экране.
///
/// Слой стоит **только** в секции суммы. Второй такой же под клавиатурой уже
/// пробовали: свет выглядывал из-под кнопки и читался не как продолжение
/// подсказки, а как второе, независимое пятно — а два пятна одновременно
/// никуда не ведут.
///
/// `mood` анимируемый: `.animation(_:value:)` снаружи даёт плавный переход
/// вместо скачка. Частоты синусов при этом фиксированы — если менять скорость
/// времени, у них скачет фаза, и переход читается рывком.
struct AmbientMoundsField: View, Animatable {
    /// 0…2, см. описание выше. Дробные значения — середина перехода.
    var mood: Double

    var animatableData: Double {
        get { mood }
        set { mood = newValue }
    }

    /// Ширина холмов долей кадра. Узкие намеренно: если сделать их широкими, два
    /// холма сливаются в одно ровное пятно, и тогда сплющивание уже не
    /// прочитать — меняется только яркость, а не форма.
    private let spread = 0.18
    /// Высота холмов долей кадра в спокойном состоянии.
    private let lift = 0.62

    /// Отсчёт времени свой, а не абсолютный: `timeIntervalSinceReferenceDate`
    /// это ~7,8·10⁸, и во `float` шейдера от него не остаётся ничего — синусы
    /// встают намертво.
    @State private var start = Date()

    var body: some View {
        GeometryReader { geometry in
            TimelineView(.animation) { context in
                let time = context.date.timeIntervalSince(start)
                Rectangle()
                    .colorEffect(
                        ShaderLibrary.ambientMounds(
                            .float2(geometry.size),
                            .float(Float(time)),
                            .float(Float(squash)),
                            .float(Float(opacity)),
                            .float(Float(warmth)),
                            .float(Float(swell)),
                            .float(Float(spread)),
                            .float(Float(lift))
                        )
                    )
            }
        }
        .allowsHitTesting(false)
        // Слой декоративный: озвучивать его нечем, а фокус он бы перехватывал.
        .accessibilityHidden(true)
    }

    // MARK: Настроение → параметры

    /// Кусочная интерполяция по трём опорным точкам: 0 → покой, 1 → ввод,
    /// 2 → нехватка.
    private func stage(_ idle: Double, _ calm: Double, _ alert: Double) -> Double {
        let m = min(max(mood, 0), 2)
        return m <= 1 ? idle + (calm - idle) * m : calm + (alert - calm) * (m - 1)
    }

    private var squash: Double {
        // В спокойном состоянии не ровный ноль: чуть подобранная высота даёт
        // запас, за счёт которого сплющивание читается как движение, а не как
        // просто «стало ярче».
        stage(0, 0.08, 1)
    }

    private var opacity: Double {
        // Тревоге нужен запас: до нижней кромки доходит меньше половины заданной
        // прозрачности, потому что свет там уже размыт сплющиванием. Поэтому
        // третье число выглядит непропорционально большим — на экране это не
        // «непрозрачный оранжевый», а примерно треть от него.
        stage(0.10, 0.22, 0.75)
    }

    private var warmth: Double {
        // Цвет появляется только на нехватке — и ведёт к кнопке, которая в этот
        // же момент становится оранжевой. Серый с оранжевым, в отличие от лайма,
        // смешивается чисто, поэтому здесь можно уходить почти в полный цвет.
        stage(0, 0, 0.9)
    }

    private var swell: Double {
        // Выше 1 в шейдере просыпается быстрая дрожь.
        stage(0.55, 1.0, 1.9)
    }
}

#Preview("Настроения") {
    VStack(spacing: WBSpace.x1) {
        ForEach([0.0, 1.0, 2.0], id: \.self) { mood in
            ZStack(alignment: .bottom) {
                AmbientMoundsField(mood: mood)
                Text(["покой", "ввод", "не хватает"][Int(mood)])
                    .font(WBFont.description)
                    .foregroundStyle(WBColor.textPrimary)
                    .padding(WBSpace.x3)
            }
            .frame(height: 200)
            .background(WBColor.bgBase, in: RoundedRectangle(cornerRadius: WBRadius.x5))
        }
    }
    .padding(WBSpace.x1)
    .background(WBColor.bgMinus1)
}
